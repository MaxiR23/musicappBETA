# services/db_protocol.py
from __future__ import annotations
from typing import Any, Protocol, runtime_checkable


class QueryBuilder(Protocol):
    """Representa el query builder fluent de Supabase."""
    def select(self, columns: str = "*") -> "QueryBuilder": ...
    def insert(self, data: dict | list) -> "QueryBuilder": ...
    def upsert(self, data: dict | list, *, on_conflict: str = "") -> "QueryBuilder": ...
    def update(self, data: dict) -> "QueryBuilder": ...
    def delete(self) -> "QueryBuilder": ...

    def eq(self, column: str, value: Any) -> "QueryBuilder": ...
    def neq(self, column: str, value: Any) -> "QueryBuilder": ...
    def in_(self, column: str, values: list) -> "QueryBuilder": ...
    def order(self, column: str, *, desc: bool = False) -> "QueryBuilder": ...
    def limit(self, count: int) -> "QueryBuilder": ...
    def single(self) -> "QueryBuilder": ...

    def execute(self) -> Any: ...

class RpcBuilder(Protocol):
    """Representa el resultado de .rpc() de Supabase."""
    def execute(self) -> Any: ...

@runtime_checkable
class DBClient(Protocol):
    """
    Interfaz mínima del cliente de base de datos.
    Compatible con supabase-py Client sin necesidad de herencia.

    Uso en producción:
        from services.supabase_service import supabase_service as sb
        result = my_function(db=sb)

    Uso en tests:
        result = my_function(db=MockDB())
    """

    def table(self, table_name: str) -> QueryBuilder: ...
    def rpc(self, fn: str, params: dict | None = None) -> RpcBuilder: ...